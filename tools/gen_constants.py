def lit(s: str) -> str:
    out = []
    for ch in s:
        o = ord(ch)
        if ch == "\\": out.append("\\\\")
        elif ch == '"': out.append('\\"')
        elif ch == "\n": out.append("\\n")
        elif ch == "\t": out.append("\\t")
        elif ch == "\r": out.append("\\r")
        elif o < 0x20 or o == 0x7f: out.append("\\u%04x" % o)
        elif o < 0x80: out.append(ch)
        elif unicodedata.category(ch)[0] in "LN" or ch == "€": out.append(ch)
        elif o > 0xffff: out.append("".join("\\u%04x" % u for u in ch.encode("utf-16-be").hex_units()) if False else "".join("\\u%04x" % c for c in (0xd800 + ((o - 0x10000) >> 10), 0xdc00 + ((o - 0x10000) & 0x3ff))))
        else: out.append("\\u%04x" % o)
    return '"' + "".join(out) + '"'

def flags(p):
    f = []
    if p.flags & re.IGNORECASE: f.append("PyRegex.IGNORECASE")
    if p.flags & re.DOTALL: f.append("PyRegex.DOTALL")
    return " | ".join(f) or "0"

def jname(n): return n.lstrip("_")

def pattern_const(name, p, indent="    "):
    return f"{indent}static final PyPattern {jname(name)} =\n{indent}        PyRegex.compile({lit(p.pattern)}, {flags(p)});\n"

