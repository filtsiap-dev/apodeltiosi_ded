# ----------------------------------------------------------------- Prompts text
core = pr._PROMPT_CORE
assert pr.SYSTEM_PROMPT_PASS1.startswith(core) and pr.SYSTEM_PROMPT_PASS2.startswith(core)
def block(s, indent=" " * 12):
    # Java text block that evaluates to exactly s (no trailing newline).
    body = []
    for line in s.split("\n"):
        line = line.replace("\\", "\\\\").replace('"""', '\\"""')
        if line.endswith(" "): line = line[:-1] + "\\s"
        body.append(indent + line if line else "")
    return '"""\n' + "\n".join(body) + '"""'
