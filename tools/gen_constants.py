# ----------------------------------------------------------------- IBAN registry (python-stdnum)
import stdnum, os
dat = Path(os.path.dirname(stdnum.__file__)) / "iban.dat"
entries = []
for raw in dat.read_text(encoding="utf-8").splitlines():
    if not raw or raw.startswith("#"): continue
    cc = raw.split()[0]
    m = re.search(r'bban="([^"]*)"', raw)
    entries.append((cc, m.group(1) if m else ""))
lines = [HEADER.format(src="python-stdnum %s stdnum/iban.dat" % stdnum.__version__),
         "package dev.filtsiap.ded.anonymizer;\n\n",
         "import java.util.Map;\n\n",
         "/** BBAN structures per country, from the IBAN registry python-stdnum validates against. */\n",
         "final class IbanRegistry {\n\n",
         "    /** Country code to BBAN structure ({@code n} digits, {@code a} upper letters, {@code c} alphanumerics). */\n",
         "    static final Map<String, String> BBAN_STRUCTURE = Map.ofEntries(\n"]
lines.append(",\n".join(f"            Map.entry({lit(cc)}, {lit(b)})" for cc, b in entries) + ");\n\n")
lines.append("    private IbanRegistry() {\n    }\n}\n")
(OUT / "IbanRegistry.java").write_text("".join(lines), encoding="utf-8")
print("generated IbanRegistry (%d countries)" % len(entries))
